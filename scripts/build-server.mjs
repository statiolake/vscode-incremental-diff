// Bundles the server (src/server/main.ts and the core it uses) into one file
// with no dependencies: server/incremental-diff-server.js. It is checked in,
// so a plugin manager that clones this repository (lazy.nvim) needs no build
// step, only `node`; test/serverBundle.test.ts fails when it is stale.
//   node scripts/build-server.mjs          write it
//   node scripts/build-server.mjs --check  exit 1 when it differs
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = `${root}server/incremental-diff-server.js`;
const { version } = JSON.parse(readFileSync(`${root}package.json`, "utf8"));

export async function bundle() {
  const result = await build({
    entryPoints: [`${root}src/server/main.ts`],
    bundle: true,
    platform: "node",
    target: "node18",
    format: "cjs",
    write: false,
    legalComments: "none",
    banner: { js: "#!/usr/bin/env node\n// Generated by scripts/build-server.mjs from src/server and src/core. Do not edit." },
    define: { SERVER_VERSION: JSON.stringify(version) }
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await bundle();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(out, "utf8"); } catch {}
    if (current !== text) {
      console.error("server/incremental-diff-server.js is stale: run npm run build:server");
      process.exit(1);
    }
  } else {
    writeFileSync(out, text, { mode: 0o755 });
  }
}
